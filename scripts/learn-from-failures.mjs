#!/usr/bin/env node
/**
 * learn-from-failures.mjs
 * Failure → MISTAKE learning extractor (Phase 4, D021).
 * Deterministic, zero-dependency (node built-ins only).
 *
 * Reads the already-collected failure contexts under .qe/learning/failures/
 * (written by hooks/scripts/lib/failure-capture.mjs), normalizes the recurring
 * signals (failure reasons + unchecked checklist items), counts their frequency,
 * and writes patterns seen >= THRESHOLD times to .qe/learning/mistake-candidates.md.
 *
 * It does NOT touch .qe/MISTAKE.md — promotion is user-confirmed via /Qmistake
 * (D011 user-in-the-loop). Candidate generation only.
 *
 * Exit 0 always (analysis is advisory, never a gate).
 */

import { readdirSync, readFileSync, existsSync, writeFileSync, statSync, mkdirSync } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, '..');
const FAILURES_DIR = join(ROOT, '.qe', 'learning', 'failures');
const OUT = join(ROOT, '.qe', 'learning', 'mistake-candidates.md');
const THRESHOLD = 2; // a pattern must recur at least this many times to be a candidate

/** Extracts the bullet lines under a given `## Heading` section of a CONTEXT.md. */
function sectionBullets(content, heading) {
  const re = new RegExp(`##\\s+${heading}\\s*\\r?\\n([\\s\\S]*?)(?:\\r?\\n##\\s|$)`);
  const m = content.match(re);
  if (!m) return [];
  return m[1]
    .split(/\r?\n/)
    .map(l => l.trim())
    .filter(l => l.startsWith('-'))
    .map(l => l.replace(/^-\s*(\[[ xX]\]\s*)?/, '').trim())
    .filter(Boolean);
}

/** Normalizes a signal string so cosmetic differences collapse to one key. */
function normalize(s) {
  return s
    .toLowerCase()
    .replace(/`[^`]*`/g, '')              // drop inline code (filenames etc.)
    .replace(/verify_checklist_[a-f0-9]+\.md/gi, 'verify_checklist')
    .replace(/task_request_[a-f0-9]+\.md/gi, 'task_request')
    .replace(/\b\d+\b/g, 'N')             // collapse counts
    .replace(/[^\p{L}\p{N}\s]/gu, ' ')    // strip punctuation (unicode-aware)
    .replace(/\s+/g, ' ')
    .trim();
}

// ─── collect ─────────────────────────────────────────────────────────────────

const patterns = new Map(); // normKey -> { example, kind, tasks:Set<uuid> }

/** Pulls the `task_uuid:` field from a CONTEXT.md, or a fallback derived from the dir. */
function taskUuidOf(content, sess) {
  const m = content.match(/task_uuid:\s*([^\s]+)/);
  if (m) return m[1].trim();
  const d = sess.match(/_([a-f0-9]{6,})$/i);
  return d ? d[1] : sess;
}

let contextCount = 0;
if (existsSync(FAILURES_DIR)) {
  for (const month of readdirSync(FAILURES_DIR).filter(f => /^\d{4}-\d{2}$/.test(f)).sort()) {
    const monthPath = join(FAILURES_DIR, month);
    if (!statSync(monthPath).isDirectory()) continue;
    for (const sess of readdirSync(monthPath).sort()) {
      const ctx = join(monthPath, sess, 'CONTEXT.md');
      if (!existsSync(ctx)) continue;
      contextCount++;
      const content = readFileSync(ctx, 'utf8');
      const uuid = taskUuidOf(content, sess);
      const signals = [
        ...sectionBullets(content, 'Failure Reasons').map(s => ({ kind: 'reason', text: s })),
        ...sectionBullets(content, 'Unchecked Checklist Items').map(s => ({ kind: 'unchecked', text: s })),
      ];
      for (const { kind, text } of signals) {
        if (!normalize(text)) continue;
        const key = `${kind}::${normalize(text)}`;
        const cur = patterns.get(key) || { example: text, kind, tasks: new Set() };
        cur.tasks.add(uuid);
        patterns.set(key, cur);
      }
    }
  }
}

// ─── select recurring ─────────────────────────────────────────────────────────
// Recurrence = distinct task_uuids exhibiting the pattern. A single flaky task
// captured multiple times counts once — only cross-task patterns are systemic.

const candidates = [...patterns.values()]
  .map(p => ({ ...p, count: p.tasks.size }))
  .filter(p => p.count >= THRESHOLD)
  .sort((a, b) => b.count - a.count);

// ─── write candidates ────────────────────────────────────────────────────────

const lines = [];
lines.push('# MISTAKE candidates (auto-extracted)');
lines.push('');
lines.push(`> Generated by scripts/learn-from-failures.mjs from ${contextCount} failure context(s).`);
lines.push('> Recurring patterns (>= ' + THRESHOLD + ' occurrences). Review and promote via /Qmistake.');
lines.push('> This file is advisory — nothing here is auto-written to .qe/MISTAKE.md.');
lines.push('');
if (candidates.length === 0) {
  lines.push('_No recurring failure pattern reached the threshold yet._');
} else {
  lines.push('| Tasks | Kind | Pattern (example) |');
  lines.push('|-------|------|-------------------|');
  for (const c of candidates) {
    const ex = c.example.replace(/\|/g, '\\|').slice(0, 120);
    lines.push(`| ${c.count} | ${c.kind} | ${ex} |`);
  }
}
lines.push('');
mkdirSync(dirname(OUT), { recursive: true }); // ensure .qe/learning exists on a fresh checkout
writeFileSync(OUT, lines.join('\n'), 'utf8');

console.log(`learn-from-failures: scanned ${contextCount} context(s), ${candidates.length} recurring candidate(s) → .qe/learning/mistake-candidates.md`);
process.exit(0);
